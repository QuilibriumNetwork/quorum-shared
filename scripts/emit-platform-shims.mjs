/**
 * Emit declaration shims for platform-split components.
 *
 * Every platform-split primitive has a barrel that imports the extensionless
 * specifier, because the bundlers pick the platform at build time:
 *
 *   // src/primitives/Icon/index.ts
 *   // @ts-ignore - Platform-specific files (.web.tsx/.native.tsx) resolved by bundler
 *   export { Icon } from './Icon';
 *
 * `tsc` has no such resolution. It compiles `Icon.web.tsx` to `Icon.web.d.ts`,
 * emits the barrel's specifier verbatim as `'./Icon'`, and that module does not
 * exist in `dist`. Consumers typecheck with `skipLibCheck`, so TypeScript
 * swallows the unresolved re-export and hands them `any` — for all 21
 * primitives, every prop, silently.
 *
 * That is not theoretical: twelve `<Icon name="...">` call sites in
 * quorum-desktop shipped with names outside the `IconName` union. `Icon`
 * renders null for those, so the icons were simply invisible, and `tsc`
 * reported nothing.
 *
 * This writes the missing `X.d.ts` next to each `X.web.d.ts`, re-exporting the
 * web declarations. Types only — the runtime bundles (`index.js`, `index.mjs`,
 * `index.native.js`) are untouched, and native consumers already resolve types
 * to this same web-built tree via package.json `exports`.
 */

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'fs';
import { join } from 'path';

const DIST = 'dist';

/**
 * Which components get a shim, by base name.
 *
 * Deliberately not "all of them yet". Restoring real types to a primitive
 * reveals every call site that was relying on `any`, and consumers have a lot
 * of those: enabling all 19 at once surfaced 98 pre-existing errors in
 * quorum-desktop, roughly two thirds in dev tooling. They are genuine (handlers
 * that may be undefined, `string` passed where a union is required, native-only
 * props on web components) but they are a separate cleanup, tracked in
 * quorum-desktop's
 * `.agents/issues/2026-08-06-invalid-icon-names-render-nothing-and-no-type-error-catches-them.md`.
 *
 * `Icon` is enabled because its `any` caused a shipped, user-visible bug:
 * twelve call sites passed names outside `IconName`, and `Icon` renders null for
 * those, so the icons were simply invisible with no error anywhere.
 *
 * Add the rest as their call sites are cleaned up, one at a time.
 */
const ENABLED = new Set(['Icon']);

const walk = (dir) => {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
};

if (!existsSync(DIST)) {
  console.error(`[platform-shims] no ${DIST}/ — run tsc first`);
  process.exit(1);
}

const written = [];

for (const file of walk(DIST)) {
  const match = file.match(/^(.*)\.web\.d\.ts$/);
  if (!match) continue;

  const shimPath = `${match[1]}.d.ts`;
  const baseName = shimPath.split(/[\\/]/).pop().replace(/\.d\.ts$/, '');
  if (!ENABLED.has(baseName)) continue;
  // A real (non-platform-split) declaration already there always wins.
  if (existsSync(shimPath)) continue;

  const webDecl = readFileSync(file, 'utf8');
  const webModule = `./${shimPath.split(/[\\/]/).pop().replace(/\.d\.ts$/, '')}.web`;

  const lines = [
    '// Generated by scripts/emit-platform-shims.mjs — do not edit.',
    '// Lets consumers resolve the barrel\'s extensionless platform import.',
    `export * from '${webModule}';`,
  ];
  // `export *` never carries a default; re-export it explicitly when there is one.
  if (/^\s*export default\b/m.test(webDecl)) {
    lines.push(`export { default } from '${webModule}';`);
  }

  writeFileSync(shimPath, `${lines.join('\n')}\n`, 'utf8');
  written.push(shimPath);
}

console.log(`[platform-shims] wrote ${written.length} declaration shim(s)`);
for (const p of written) console.log(`  ${p.replace(/\\/g, '/')}`);
